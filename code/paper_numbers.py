def floor_minus_ceiling():
    print("\n## Floor minus ceiling (adding the record to a prompt that already states the answer), source question, paired over worlds\n")
    for name, f in BIG:
        got = {r["episode_id"]: r for r in load("../data/runs/%s.jsonl" % f)}
        for c in CELLS:
            d = paired_diff(got, lambda k, c=c: k["question"] == "source" and k["variant"] == "floor" and k["cell"] == c,
                            lambda k, c=c: k["question"] == "source" and k["variant"] == "ceiling" and k["cell"] == c)
            print("- %s, %s: %+.3f [%+.3f, %+.3f]" % (name, PLAIN[c], *d))
    print("\n## Largest within-model swing across wordings, calibrated source question\n")
    for name, f in BIG:
        got = {r["episode_id"]: r for r in load("../data/runs/%s.jsonl" % f)}
        for group, cells in (("honest", ("stable", "world")), ("lying", ("reporter", "both"))):
            best = 0
            for c in cells:
                v = [boot(units(got, lambda k, c=c, w=w: k["question"] == "source" and k["variant"] == "cal" and k["cell"] == c and k["form"] == w))[0]
                     for w in ("commentary", "log", "minutes", "prose")]
                best = max(best, max(v) - min(v))
            print("- %s, %s situations: %.3f" % (name, group, best))


if __name__ == "__main__":
    floor_minus_ceiling()
