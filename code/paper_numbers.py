def boot(units, n=4000, seed=0):
    by = collections.defaultdict(list)
    for fam, ok in units: by[fam].append(ok)
    fams = sorted(by); rng = random.Random(seed)
    tot = sum(len(v) for v in by.values()); pt = sum(sum(v) for v in by.values()) / tot
    d = sorted(sum(sum(by[f]) for f in p) / sum(len(by[f]) for f in p)
               for p in ([rng.choice(fams) for _ in fams] for _ in range(n)))
    return pt, d[int(.025 * n)], d[int(.975 * n)], tot

def f3(t): return "%.3f [%.3f, %.3f]" % t[:3]

def units(got, pred, target="correct"):
    out = []
    for i, k in KEY.items():
        if not pred(k) or i not in got: continue
        if target == "correct":
            if k["correct"] is None: continue
            out.append((k["family_id"], got[i]["choice"] == k["correct"]))
        elif target == "honest":
            out.append((k["family_id"], got[i]["choice"] == k["accurate_label"]))
    return out

def paired_diff(got, predA, predB, n=4000, seed=0):
    """A minus B, resampling the same worlds for both."""
    A = collections.defaultdict(list); B = collections.defaultdict(list)
    for fam, ok in units(got, predA): A[fam].append(ok)
    for fam, ok in units(got, predB): B[fam].append(ok)
    fams = sorted(set(A) | set(B)); rng = random.Random(seed)
    def acc(D, p):
        x = [b for f in p for b in D.get(f, [])]; return sum(x) / len(x)
    pt = acc(A, fams) - acc(B, fams)
    d = sorted(acc(A, p) - acc(B, p) for p in ([rng.choice(fams) for _ in fams] for _ in range(n)))
    return pt, d[int(.025 * n)], d[int(.975 * n)]

